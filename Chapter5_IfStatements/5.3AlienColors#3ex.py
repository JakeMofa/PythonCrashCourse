
age = 10
if age < 2:
    print("this person is a baby")
elif 2 <= age < 4:
    print("this person is a toddler")
elif 4 <= age < 13:
    print("this person is a kid")
elif 13 <= age < 20:
    print("this person is a teenager")
elif 20 <= age < 65:
    print("this person is an adult")
else:
    print("this person is an elder")